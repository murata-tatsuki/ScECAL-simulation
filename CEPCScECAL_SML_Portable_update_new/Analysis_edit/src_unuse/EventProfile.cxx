int Number2CellID(int ID)// 0-6719 to CellID
{
	int positionID = ID%210;
	int layerID = ID/210;
	//cout << "layer : " << layerID << " position : " << positionID << endl;  
	if(	(layerID<0 || layerID>31) || (positionID<0 || positionID>210) )
	{
		cout << "@@@@@@@ INCORRECT NUMBER !! @@@@@@@@" << endl;
		exit(1);
	}
	else
		return ( layerID*1e5 + position2cell[positionID]);
}

bool IsDead(int cellID)// input CellID
{
	vector<int>::iterator it = find(deadchannel.begin(),deadchannel.end(),cellID);
	if(it==deadchannel.end())
		return false;
	else
		return true;
}

void EventProfile()
{  
	//gStyle->SetOptStat(0);
	const int LayerNo = 30;
	const double MIPEnergy = 0.305; //MeV
    const int EventNo = 1000;			// ******** change here *********//
	const int EventEnergy = 40; //GeV	// ******** change here *********//
    string EventParticle("electron");	// ******** change here *********//
	//double EnergyCut[EnergyCutSize] = {3,4,5};
	//const int EnergyCutSize = 31;				// ******** change here *********//
	//for (int i = 0 ; i < EnergyCutSize ; i++)	{EnergyCut[i] = i*0.1;}
	const int EnergyCutSize = 4;				// ******** change here *********//
	double EnergyCut[EnergyCutSize] = {0};
	for (int i = 0 ; i < EnergyCutSize ; i++)	{EnergyCut[i] = i*0.1+0.5;}

    char filename[100];
    sprintf(filename,"%s_%d_%dGeV",EventParticle.c_str(),EventNo,EventEnergy);//change here
    cout << filename << endl;

    TFile *simufile;
    TTree *simutree;
	char outputpath[100];
	TFile * fileout;
    Double_t _PrimaryEnergy;
    vector<int>*	_ScintID;
    vector<int>*	_AbsorID;
    vector<int>*	_PCBID;
    vector<double>*	 _EnergyDep;
    vector<double>*	_AbsorEnergyDep;
    vector<double>*	 _PCBEnergyDep;
	char inputpath[100];
	sprintf(inputpath,"../Result/merge_root/%s.root",filename);
    simufile = TFile::Open(inputpath);
    if(!simufile) cout << "Open file failed!"<< endl;
    simutree = (TTree*)simufile->Get("T");
    _PrimaryEnergy=0;			simutree->SetBranchAddress("PrimaryEnergy",&_PrimaryEnergy);
    _ScintID=nullptr; 			simutree->SetBranchAddress("CrystalID",&_ScintID);
    _AbsorID=nullptr;			simutree->SetBranchAddress("AbsorberID",&_AbsorID);
    _PCBID=nullptr;				simutree->SetBranchAddress("PCBID",&_PCBID);
    _EnergyDep=nullptr;			simutree->SetBranchAddress("EnergyDep",&_EnergyDep);
    _AbsorEnergyDep=nullptr;	simutree->SetBranchAddress("AbsorberEnDep",&_AbsorEnergyDep);
    _PCBEnergyDep=nullptr;		simutree->SetBranchAddress("PCBEnDep",&_PCBEnergyDep); 

	TH1F* energytotal[EnergyCutSize];
	TProfile *energypro[EnergyCutSize];
	TH2D *energy2d[EnergyCutSize];
	TProfile *hitpro[EnergyCutSize];
	TH2I *hit2d[EnergyCutSize];
	//for(int i_cut=0; i_cut < 1; i_cut++)
	for(int i_cut=0; i_cut < EnergyCutSize; i_cut++)
	{
		double EnergyCutValue = EnergyCut[i_cut];
		sprintf(outputpath,"../Result/event_profile/%s_%.1fMIP.root",filename,EnergyCutValue);
		fileout = new TFile(outputpath,"recreate");
		
		energypro[i_cut] = new TProfile(Form("energypro_%.1fMIP_cut",EnergyCutValue),"",30,0,30,0,1000);
		energy2d[i_cut] = new TH2D(Form("energy2d_%.1fMIP_cut",EnergyCutValue),"",30,0,30,5*EventEnergy>=100?5*EventEnergy:50,0,EventEnergy>=20?5*EventEnergy:10*EventEnergy);
		energytotal[i_cut] = new TH1F(Form("energytotal_%.1fMIP_cut",EnergyCutValue),"",300,1000,2500);
		//TH2D *energy2d = new TH2D("energy2d","Layer_Energy",30,0,30,5*EventEnergy>=100?5*EventEnergy:50,0,250);
		hitpro[i_cut] = new TProfile(Form("hitpro_%.1fMIP_cut",EnergyCutValue),"",LayerNo,0,LayerNo,0,1000);
		hit2d[i_cut] = new TH2I(Form("hit2d_%.1fMIP_cut",EnergyCutValue),"",LayerNo,0,LayerNo,100,0,100);

		int TreeEntryNo = simutree->GetEntries();
		for(int i_entry = 0; i_entry < TreeEntryNo; i_entry++)
		{
			double layersum[LayerNo] = {0};
			double energysum = {0};
			int hitnosum[LayerNo] = {0};	
			simutree->GetEntry(i_entry);
			for(int i_vector = 0; i_vector < _EnergyDep->size(); i_vector++)
			{
				int layerid = _ScintID->at(i_vector)/210;
				int cellid = Number2CellID(_ScintID->at(i_vector)); 
				if(layerid >= LayerNo) continue;	// jiaxuan : 30 layers
				if(IsDead(cellid)) { continue;}
				if(_EnergyDep->at(i_vector) > EnergyCutValue * MIPEnergy) //over threshold
				{
					layersum[layerid] += _EnergyDep->at(i_vector);
					energysum +=  _EnergyDep->at(i_vector);
					hitnosum[layerid]++; 
				}
			}
			if(i_entry<10)
			{
				cout << i_entry << "	" <<  energysum << endl;
			}
			energytotal[i_cut]->Fill(energysum);
			for(int i_layer = 0; i_layer < LayerNo; i_layer++)
			{	
				//cout <<  "layer : " << i_layer << " layersum[i_layer]" << layersum[i_layer] << endl; 
				energy2d[i_cut]->Fill(i_layer,layersum[i_layer],1);
				energypro[i_cut]->Fill(i_layer,layersum[i_layer],1);
				hit2d[i_cut]->Fill(i_layer,hitnosum[i_layer],1);
				hitpro[i_cut]->Fill(i_layer,hitnosum[i_layer],1);
			}
		}	
		
		fileout->cd();
		energy2d[i_cut]->SetTitle(Form("%d_GeV_%s_energydep_%.1fMIP_cut",EventEnergy,EventParticle.c_str(),EnergyCutValue));
		energy2d[i_cut]->GetXaxis()->SetTitle("LayerNo");
		energy2d[i_cut]->GetYaxis()->SetTitle("Energy/MeV");
		energypro[i_cut]->SetLineWidth(2);
		energypro[i_cut]->SetLineColor(2);
		energypro[i_cut]->SetMarkerColor(2);
		energypro[i_cut]->GetXaxis()->SetTitle("LayerNo");
		energypro[i_cut]->GetYaxis()->SetTitle("Energy/MeV");
		
		energy2d[i_cut]->Write();
		energypro[i_cut]->Write();
		energytotal[i_cut]->SetLineColor(kRed);
		energytotal[i_cut]->Write();

		hit2d[i_cut]->SetTitle(Form("%d_GeV_%s_hitNo_%.1fMIP_cut",EventEnergy,EventParticle.c_str(),EnergyCutValue));
		hit2d[i_cut]->GetXaxis()->SetTitle("LayerNo");
		hit2d[i_cut]->GetYaxis()->SetTitle("HitNo");
		//hit2d[i_cut]->GetZaxis()->SetRangeUser(0,2000);
		
		hitpro[i_cut]->SetLineWidth(2);
		hitpro[i_cut]->SetLineColor(2);
		hitpro[i_cut]->SetMarkerColor(2);
		hit2d[i_cut]->Write();
		hitpro[i_cut]->Write();

		fileout->Close();
		cout << "Outfile :  " << outputpath << endl;
	}
//**********************************************************************
//**********************************************************************
}
