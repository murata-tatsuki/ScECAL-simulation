//void HitStatistic(string fileinname,string fileoutname)
void HitStatistics()
{
	//TString FileInName(fileinname);
	//TString FileOutName(fileoutname);
	TString FileInName("../Result/merge_root_convert/electron_1000_40GeV.root");
	TString FileOutName("../Result/hit_statistics/electron_1000_40GeV.root");
	
	TFile* filein = TFile::Open(FileInName,"READ");
	if(!filein) cout << "NO FILE " << endl;
	//TTree* treein = (TTree*)filein->Get("Simu_Hit");
	TTree* treein = (TTree*)filein->Get("Calib_Hit");
	if(!treein) cout << "NO TREE " << endl;
	
	vector<int>*	_cellID = nullptr;
	vector<double>*	_hitEnergy = nullptr;
	vector<double>* _hitX = nullptr;
	vector<double>* _hitY = nullptr;
	vector<double>* _hitZ = nullptr;
	treein->SetBranchAddress("CellID",&_cellID);
	treein->SetBranchAddress("Hit_Energy",&_hitEnergy);
	treein->SetBranchAddress("Hit_X",&_hitX);
	treein->SetBranchAddress("Hit_Y",&_hitY);
	treein->SetBranchAddress("Hit_Z",&_hitZ);

	TFile* fileout = new TFile(FileOutName,"RECREATE");

	const int LayerNu = 32;
	TH2D* even[LayerNu/2];
	TH2D* odd[LayerNu/2];
	TH2D* even_energy[LayerNu/2];
	TH2D* odd_energy[LayerNu/2];
	TH1D* all_energy = new TH1D("TotalEnergy","TotalEnergy",200,0,2000);
	for(int i=0; i < LayerNu/2; i++)
	{
		//even[i] = new TH2D(Form("layer%d",2*i),Form("layer%d",2*i),5,-112.5,112.5,42,-105,105);
		//odd[i] = new TH2D(Form("layer%d",2*i+1),Form("layer%d",2*i+1),42,-105,105,5,-112.5,112.5);
		even[i] = new TH2D(Form("layer%d",2*i),Form("layer%d",2*i),5,-111.5,111.5,42,-111.1,111.5);
		even_energy[i] = new TH2D(Form("layer%d_energy",2*i),Form("layer%d_energy",2*i),5,-111.5,111.5,42,-111.1,111.5);
		odd[i]  = new TH2D(Form("layer%d",2*i+1),Form("layer%d",2*i+1),42,-111.1,111.5,5,-111.5,111.5);
		odd_energy[i]  = new TH2D(Form("layer%d_energy",2*i+1),Form("layer%d_energy",2*i+1),42,-111.1,111.5,5,-111.5,111.5);
	}

	cout <<"ENTRIES : " << treein->GetEntries() << endl;
	for(int i_entry = 0; i_entry < 1000; i_entry++)
	//for(int i_entry = 0; i_entry < treein->GetEntries(); i_entry++)
	{
		//if(i_entry%10000==0) cout << i_entry << endl;
		treein->GetEntry(i_entry);
		double totalenergy = 0;
		for(unsigned int i_vector = 0; i_vector < _cellID->size(); i_vector++)
		{
			int cellid	  = _cellID->at(i_vector);
			int layerid	  = cellid/100000;
			//cout << layerid << endl;
			double energy = _hitEnergy->at(i_vector);
			if(energy<0.8*0.305) 	continue;
			if(layerid >= 30) 		continue;	// jiaxuan : 30 layers
			if(IsDead(cellid))  	continue;
			double xpos   = _hitX->at(i_vector);
			double ypos   = _hitY->at(i_vector);
			totalenergy += energy;
			if(layerid%2==0)
			{
				even[layerid/2]->Fill(xpos,ypos);
				even_energy[layerid/2]->Fill(xpos,ypos,energy);
			}
			else
			{
				odd[(layerid-1)/2]->Fill(xpos,ypos);
				odd_energy[(layerid-1)/2]->Fill(xpos,ypos,energy);
			}
		}
		all_energy->Fill(totalenergy);
	}
	
	fileout->cd();
	TCanvas* c_hitno_whole_even  = new TCanvas("Hit_Statistics_Even","Hit_Statistics_Even",1400,1200);
	TCanvas* c_energy_whole_even = new TCanvas("Hit_Energy_Even","Hit_Energy_Even",1400,1200);
	TCanvas* c_hitno_whole_odd   = new TCanvas("Hit_Statistics_Odd","Hit_Statistics_Odd",1400,1200);
	TCanvas* c_energy_whole_odd  = new TCanvas("Hit_Energy_Odd","Hit_Energy_Odd",1400,1200);
	//filename.erase(filename.begin(),filename.begin()+5);
	//filename.erase(filename.end()-5,filename.end());
	c_hitno_whole_even  ->Divide(4,4);
	c_energy_whole_even ->Divide(4,4);
	c_hitno_whole_odd   ->Divide(4,4);
	c_energy_whole_odd  ->Divide(4,4);
	for(int i_layer = 0; i_layer < LayerNu; i_layer++)
	{
		gStyle->SetOptStat(0);
		if(i_layer%2==0)
		{
			c_hitno_whole_even->cd(i_layer/2+1);
			gPad->SetLogz();
			even[i_layer/2]->GetZaxis()->SetRangeUser(0,1000);
			even[i_layer/2]->GetXaxis()->SetTitle("position_X");
			even[i_layer/2]->GetYaxis()->SetTitle("position_Y");
			even[i_layer/2]->Draw("colz");
			even[i_layer/2]->Write();
			c_energy_whole_even->cd(i_layer/2+1);
			gPad->SetLogz();
			even_energy[i_layer/2]->GetZaxis()->SetRangeUser(0,20000);
			even_energy[i_layer/2]->GetXaxis()->SetTitle("position_X");
			even_energy[i_layer/2]->GetYaxis()->SetTitle("position_Y");
			even_energy[i_layer/2]->Draw("colz");
			even_energy[i_layer/2]->Write();
		}
		else
		{
			c_hitno_whole_odd->cd((i_layer-1)/2+1);
			gPad->SetLogz();
			odd[(i_layer-1)/2]->GetZaxis()->SetRangeUser(0,1000);
			odd[(i_layer-1)/2]->GetXaxis()->SetTitle("position_X");
			odd[(i_layer-1)/2]->GetYaxis()->SetTitle("position_Y");
			odd[(i_layer-1)/2]->Draw("colz");
			odd[(i_layer-1)/2]->Write();
			c_energy_whole_odd->cd((i_layer-1)/2+1);
			gPad->SetLogz();
			odd_energy[(i_layer-1)/2]->GetZaxis()->SetRangeUser(0,20000);
			odd_energy[(i_layer-1)/2]->GetXaxis()->SetTitle("position_X");
			odd_energy[(i_layer-1)/2]->GetYaxis()->SetTitle("position_Y");
			odd_energy[(i_layer-1)/2]->Draw("colz");
			odd_energy[(i_layer-1)/2]->Write();
		}

		if(i_layer==(LayerNu-1)) 
		{
			c_hitno_whole_even  ->Write();
			c_energy_whole_even ->Write();
			c_hitno_whole_odd   ->Write();
			c_energy_whole_odd  ->Write();
		}
	}
	all_energy->Write();

}
 
